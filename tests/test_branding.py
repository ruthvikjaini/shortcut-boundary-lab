"""No watermarks / AI branding in shipped code, docs, or outputs."""

from pathlib import Path

BANNED = ["Muse", "AI-generated", "generated by AI", "watermark",
          "Claude", "Anthropic"]

ROOT = Path(__file__).resolve().parent.parent


def _shipped_files():
    for p in ROOT.rglob("*"):
        if p.is_file() and p.suffix in (".py", ".md", ".toml", ".yml",
                                        ".txt", ".json"):
            rel = p.relative_to(ROOT)
            if rel.parts[0] in ("docs", "results", ".git"):
                continue
            if ".venv" in rel.parts or "__pycache__" in rel.parts:
                continue
            if p.name == "test_branding.py":
                continue  # the token list itself lives here
            yield p


def test_no_branding_in_shipped_files():
    bad = []
    for p in _shipped_files():
        text = p.read_text(errors="ignore")
        for token in BANNED:
            if token in text:
                bad.append(f"{p.relative_to(ROOT)}: {token}")
    assert not bad, bad
